// Mounts this checkout as an MCP bridge inside a DeepSeek Harness profile, so DSH
// sessions can call the agents_* tools and follow a run without the panel.
//
//   npm run connect:dsh                        # generate the bundle, install it
//   npm run connect:dsh -- --profile web       # a CLI-managed profile
//   npm run connect:dsh -- --remove
//
// The bundle is generated outside the repo (it carries absolute paths), then
// installed with `dsh plugin <profile> add`, which runs pnpm in the profile —
// the same route every other DSH plugin uses. Nothing here edits the profile
// patch by hand.
//
// The desktop profile is managed by the DSH window itself, so the launcher
// refuses CLI installs there: the script then only generates the bundle and
// prints the path to install from DSH (Plugins → install from folder).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { stateDirectory } from '../src/engine/store.js';

const repo = resolve(fileURLToPath(new URL('..', import.meta.url)));
const packageName = 'dsh-agents-mcp';

function dshCli(env) {
  const npm = env.APPDATA && join(env.APPDATA, 'npm', 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js');
  if (npm && existsSync(npm)) return npm;
  throw new Error('Could not find the DSH launcher. Install it with: npm i -g @deepseek-ai/dsh');
}

function bundle(dir) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'package.json'), JSON.stringify({
    name: packageName,
    version: '1.0.0',
    private: true,
    description: 'Mounts the local Agents-MCP server as an MCP bridge inside this DSH profile.',
    dsh: { bundle: { patch: './cordis.patch.yml' } },
  }, null, 2) + '\n');
  const quote = value => "'" + String(value).replace(/'/g, "''") + "'";
  writeFileSync(join(dir, 'cordis.patch.yml'), [
    '# Generated by `npm run connect:dsh` from the Agents-MCP checkout at:',
    '#   ' + repo,
    '# Every tool becomes mcp__agents-mcp__<ToolName> in DSH sessions.',
    '- insert:',
    '    - id: agents-mcp-bridge',
    '      name: "@deepseek-ai/dsh-mcp-client"',
    '      config:',
    '        serverName: agents-mcp',
    '        transport: stdio',
    '        command: ' + quote(process.execPath),
    '        args:',
    '          - ' + quote(join(repo, 'bin', 'agents-mcp.js')),
    '          - "--mcp=stdio"',
    '        cwd: ' + quote(repo),
    '        # A flow step can run a whole agent turn; keep the call alive long enough.',
    '        toolCallTimeoutMs: 900000',
    '        # A broken bridge must never stop DSH from booting.',
    '        failOnStartupError: false',
    '        reconnect:',
    '          enabled: true',
    '          initialDelayMs: 500',
    '          maxDelayMs: 30000',
    '          maxAttempts: 10',
    '',
  ].join('\n'));
  return dir;
}

const { values } = parseArgs({ options: {
  profile: { type: 'string', default: 'desktop' },
  dir: { type: 'string' },
  remove: { type: 'boolean' },
  help: { type: 'boolean' },
} });

if (values.help) {
  process.stdout.write('Usage: connect-dsh [--profile NAME] [--dir PATH] [--remove]\n');
  process.exit(0);
}

const env = process.env;
const target = values.dir ?? join(stateDirectory(undefined, env), 'dsh-bundle');
if (!values.remove) bundle(target);

const cli = dshCli(env);
const result = spawnSync(process.execPath,
  [cli, 'plugin', '--profile', values.profile, values.remove ? 'remove' : 'add', packageName],
  { encoding: 'utf8', env, cwd: repo });
const output = (result.stdout ?? '') + (result.stderr ?? '');

if (result.status === 0) {
  process.stdout.write(values.remove
    ? 'Removed ' + packageName + ' from the ' + values.profile + ' profile.\n'
    : 'Installed ' + packageName + ' into the ' + values.profile + ' profile from ' + target + '.\n'
      + 'Restart DeepSeek Harness, then ask it to call agents_status.\n');
  process.exit(0);
}
if (/managed exclusively by the Electron application/.test(output)) {
  process.stdout.write('The ' + values.profile + ' profile is owned by the DSH window, so the launcher '
    + 'refuses CLI installs.\n' + (values.remove
      ? 'Remove it from DSH: Plugins → ' + packageName + ' → uninstall.\n'
      : 'The bundle is ready at:\n  ' + target + '\n'
        + 'Install it from DSH: Plugins → install from folder → that path (or tell DSH itself to install it).\n'));
  process.exit(0);
}
process.stderr.write(output);
process.stderr.write('Agents-MCP: dsh plugin failed (' + result.status + '). '
  + 'Close the DSH window and retry if the profile was locked.\n');
process.exit(1);
